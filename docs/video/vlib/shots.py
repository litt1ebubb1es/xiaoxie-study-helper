def shot_at(t: float) -> tuple[Shot, float]:
    for s in SHOTS:
        if s.t0 <= t < s.t1:
            return s, t - s.t0
    return SHOTS[-1], t - SHOTS[-1].t0


def check() -> None:
    assert SHOTS[0].t0 == 0.0
    assert abs(SHOTS[-1].t1 - DUR) < 1e-6, SHOTS[-1].t1
    for a, b in zip(SHOTS, SHOTS[1:]):
        assert abs(a.t1 - b.t0) < 1e-9, (a.name, b.name)
    for s in SHOTS:
        for edge in (s.t0, s.t1):
            assert abs(edge * 2 - round(edge * 2)) < 1e-9, f"{s.name} 切点不在拍上：{edge}"
        if isinstance(s.plate, F.AppFootage):
            assert s.plate.src1 - s.plate.src0 <= s.dur + 1e-9, \
                f"{s.name} 源片段比版面还长：{s.plate.src1 - s.plate.src0:.1f}s > {s.dur:.1f}s"


check()

